-- 结构：单表 (user_id, key) 唯一 → 每用户每类一行 LLM 合并摘要（同 key 更新，不追加行）
-- 命名：uk_/ix_/fk_/ck_（编码规范 §29）；回滚见 .harness/changes/user-memory/rollback.sql

CREATE TABLE user_memory (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           INTEGER      NOT NULL,
    key               VARCHAR(30)  NOT NULL,
    value             TEXT         NOT NULL,
    source_session_id INTEGER,
    created_at        TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at        TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT ck_user_memory_key CHECK (key IN ('preference', 'restriction', 'habit'))
);
COMMENT ON TABLE user_memory IS '跨会话用户画像（F-B2；每用户每类一行 LLM 合并摘要；隐私红线：不存姓名/账号等敏感信息，用户可查看可删除）';
COMMENT ON COLUMN user_memory.key IS '画像类别：preference 偏好茶类/口味；restriction 忌口/禁忌；habit 常用茶器/冲泡习惯';
COMMENT ON COLUMN user_memory.value IS '提炼后的一句话摘要（每类 ≤50 字）；同 key 更新合并写回，不追加行';
COMMENT ON COLUMN user_memory.source_session_id IS '最近一次抽取来源会话（审计可溯）；不建 FK——会话删除后画像按隐私红线仍保留，直到用户显式删除';

CREATE UNIQUE INDEX uk_user_memory_user_key ON user_memory (user_id, key);
CREATE INDEX ix_user_memory_user_id ON user_memory (user_id);
ALTER TABLE user_memory ADD CONSTRAINT fk_user_memory_user_id FOREIGN KEY (user_id) REFERENCES users (id);
